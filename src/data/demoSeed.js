function deterministicDemoUuid(prefixHex, index) {
  const hex = (index + 1).toString(16).padStart(4, '0');
  return `d3a05700-${prefixHex}-4000-8000-00000000${hex}`;
}

export function buildDemoRegistros() {
  const mapList = (list, codigoEquipo, prefixHex) =>
    list.map((item, idx) => {
      const horas = round1(Math.max(0, item.hf - item.hi));
      const rendimiento = horas > 0 ? round2(item.mat / horas) : 0;
      const ts = `${item.fecha}T${item.turno === 'DIA' ? '18:30:00' : '06:30:00'}-05:00`;
      return {
        id: deterministicDemoUuid(prefixHex, idx),
        codigo_equipo: codigoEquipo,
        fecha: item.fecha,
        turno: item.turno,
        horometro_inicial: round1(item.hi),
        horometro_final: round1(item.hf),
        horas_trabajadas: horas,
        material_fracturado: item.mat,
        rendimiento,
        area_trabajo: item.area,
        operador: item.turno === 'DIA' ? 'Operador Guardia Día' : 'Operador Guardia Noche',
        observaciones: item.mat === 0 ? 'Horas sin fractura registrada' : '',
        hora_peru: item.turno === 'DIA' ? '18:30:00' : '06:30:00',
        creado_en: ts,
        actualizado_en: ts,
        dispositivo: 'Ejemplo PICOTÓN',
        estado: 'demo',
        es_demo: true,
        eliminado: false
      };
    });

  return [
    ...mapList([...DEMO_STREX01_JUL_OCT, ...DEMO_STREX01_NOV], 'STREX01', '0001'),
    ...mapList([...DEMO_STREX02_OCT, ...DEMO_STREX02_NOV], 'STREX02', '0002')
  ];
}

